def _load_registry() -> Dict[str, TabSpecRecord]:
    reg: Dict[str, TabSpecRecord] = {t.slug: t for t in INITIAL_TABS}
    if CUSTOM_TABS_FILE.exists():
        try:
            raw = json.loads(CUSTOM_TABS_FILE.read_text(encoding="utf-8"))
            for item in raw:
                spec = TabSpecRecord(**item)
                reg[spec.slug] = spec
        except Exception:
            pass
    return reg


TAB_REGISTRY: Dict[str, TabSpecRecord] = _load_registry()


def list_tabs(include_extended: bool = True) -> List[TabSpecRecord]:
    items = list(TAB_REGISTRY.values())
    if not include_extended:
        items = [t for t in items if t.core]
    items.sort(key=lambda t: t.index)
    return items


def get_tab(slug: str) -> Optional[TabSpecRecord]:
    return TAB_REGISTRY.get(slug)


def register_dynamic_tab(spec: TabSpecRecord) -> TabSpecRecord:
    """Persist a dynamically added tab so it survives restarts."""
    TAB_REGISTRY[spec.slug] = spec
    custom_only = [t.model_dump() for t in TAB_REGISTRY.values() if t.index > 28 or t.slug not in {x.slug for x in INITIAL_TABS}]
    CUSTOM_TABS_FILE.write_text(json.dumps(custom_only, indent=2), encoding="utf-8")
    return spec
