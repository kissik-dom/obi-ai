import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
export async function generatePdf(title: string, body: string): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.TimesRoman);
  const bold = await doc.embedFont(StandardFonts.TimesRomanBold);
  const pageWidth = 595.28, pageHeight = 841.89, margin = 56, maxWidth = pageWidth - margin * 2, fontSize = 11, lineHeight = 16;
  let page = doc.addPage([pageWidth, pageHeight]);
  page.drawText(wrap(title, bold, 24, maxWidth)[0] || title, { x: margin, y: pageHeight - 200, size: 24, font: bold, color: rgb(0.1, 0.1, 0.1) });
  page.drawText("Generated by Obi AI", { x: margin, y: pageHeight - 230, size: 12, font, color: rgb(0.4, 0.4, 0.4) });
  page = doc.addPage([pageWidth, pageHeight]);
  let y = pageHeight - margin;
  for (const para of body.split(/\n/)) {
    const isHeading = /^#{1,6}\s/.test(para);
    const cleaned = para.replace(/^#{1,6}\s/, "");
    const useFont = isHeading ? bold : font, useSize = isHeading ? 14 : fontSize;
    const lines = cleaned.length ? wrap(cleaned, useFont, useSize, maxWidth) : [""];
    for (const line of lines) {
      if (y < margin + lineHeight) { page = doc.addPage([pageWidth, pageHeight]); y = pageHeight - margin; }
      page.drawText(line, { x: margin, y, size: useSize, font: useFont, color: rgb(0.1, 0.1, 0.1) });
      y -= isHeading ? lineHeight + 4 : lineHeight;
    }
  }
  return doc.save();
}
function wrap(text: string, font: any, size: number, maxWidth: number): string[] {
  const words = text.split(/\s+/); const lines: string[] = []; let current = "";
  for (const w of words) {
    const test = current ? current + " " + w : w;
    if (font.widthOfTextAtSize(test, size) > maxWidth && current) { lines.push(current); current = w; }
    else current = test;
  }
  if (current) lines.push(current);
  return lines;
}
